/**
 * Writes the Supabase Auth email templates (src/lib/auth-emails.ts) to
 * supabase/templates/, with their subjects in supabase/templates/README.md.
 * Run after changing the layout or the wording, then paste them into the
 * dashboard:  pnpm --filter @workspace/api-server run auth-templates
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

// Images and links must point at the live site, whatever this machine's APP_URL is.
delete process.env.APP_URL;
const { AUTH_TEMPLATES, authTemplateHtml } = await import("../src/lib/auth-emails");

const out = resolve(dirname(fileURLToPath(import.meta.url)), "../../../supabase/templates");
mkdirSync(out, { recursive: true });
for (const t of AUTH_TEMPLATES) writeFileSync(join(out, t.file), authTemplateHtml(t) + "\n");

writeFileSync(join(out, "README.md"), `# Supabase Auth email templates

Generated by \`artifacts/api-server/scripts/auth-email-templates.ts\` from
\`src/lib/auth-emails.ts\`, in the same layout as every other gradefarm. email.
Don't edit these files by hand: change the wording there and run

    pnpm --filter @workspace/api-server run auth-templates

To use them, in the Supabase dashboard open Authentication → Emails →
Templates, and for each one below set the subject and paste the file's HTML
as the body. Supabase only sends custom templates through custom SMTP
(Authentication → Emails → SMTP Settings), for example Resend's
(smtp.resend.com, port 465, user \`resend\`, an API key as the password, sender
notifications@gradefarm.com.au).

| Template | Subject | File |
| :-- | :-- | :-- |
${AUTH_TEMPLATES.map((t) => `| ${t.dashboardName} | ${t.subject} | \`${t.file}\` |`).join("\n")}
`);
console.log(`Wrote ${AUTH_TEMPLATES.length} templates to ${out}`);
